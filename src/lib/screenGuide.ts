const BY_PATH = new Map(SCREEN_GUIDES.map((g) => [g.path, g]));

/**
 * המדריך של המסך שהנתיב שייך אליו.
 *
 * מסכי פירוט (למשל כרטיס תלמיד) אינם רשומים בעצמם, ולכן נבחרת ההתאמה
 * הארוכה ביותר שהנתיב מתחיל בה - כך גם כרטיס תלמיד מקבל את העזרה של
 * מסך התלמידים במקום כלום.
 */
export function guideForPath(pathname: string): ScreenGuide | null {
  if (BY_PATH.has(pathname)) return BY_PATH.get(pathname)!;
  let best: ScreenGuide | null = null;
  for (const g of SCREEN_GUIDES) {
    if (pathname.startsWith(g.path + "/") && (!best || g.path.length > best.path.length)) best = g;
  }
  return best;
}
